"""Lossless signed coefficient storage and deterministic C/Rust source generation."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EVAL_FEATURES = (
    "material_pawn", "material_knight", "material_bishop", "material_rook", "material_queen",
    "center_pawn", "center_knight", "center_bishop", "center_rook", "center_queen", "center_king",
    "pawn_advance", "doubled_pawn_excess", "isolated_pawns", "bishop_pair", "tempo",
)
ORDER_FEATURES = (
    "victim_value", "attacker_value_if_capture", "promotion_gain", "center_delta", "pawn_rank_delta",
)


def encode_signed(values):
    out = bytearray()
    for value in values:
        if type(value) is not int or not -32768 <= value <= 32767:
            raise ValueError("coefficient must be a signed 16-bit integer")
        u = 2 * value if value >= 0 else -2 * value - 1
        while u >= 128:
            out.append((u & 127) | 128)
            u >>= 7
        out.append(u)
    return bytes(out)


def decode_signed(data, count=None):
    """Strict canonical decoder used by build checks, not the fixed-stream runtime."""
    values, u, shift = [], 0, 0
    for byte in data:
        if type(byte) is not int or not 0 <= byte <= 255:
            raise ValueError("invalid byte")
        u |= (byte & 127) << shift
        if u > 65535 or shift > 14:
            raise ValueError("encoded coefficient outside signed 16-bit range")
        if byte & 128:
            shift += 7
        else:
            if shift and not byte:
                raise ValueError("noncanonical overlong coefficient")
            values.append(-(u // 2) - 1 if u & 1 else u // 2)
            u, shift = 0, 0
    if shift:
        raise ValueError("truncated coefficient")
    if count is not None and len(values) != count:
        raise ValueError("coefficient count mismatch")
    return values


def load_model(path=HERE / "frozen.json"):
    def no_float(_):
        raise ValueError("floating point is not allowed in the frozen integer model")

    model = json.loads(Path(path).read_text(encoding="utf-8"), parse_float=no_float,
                       parse_constant=no_float)
    if model.get("schema") != "rove4k.integer-model.v1":
        raise ValueError("unknown model schema")
    if model.get("piece_order") != "PNBRQK" or model.get("perspective") != "white-minus-black":
        raise ValueError("unknown feature perspective or piece order")
    if model.get("scale") != "centipawns" or model.get("encoding") != (
        "signed-16-zigzag-uleb128-evaluation-then-ordering"
    ):
        raise ValueError("unknown score scale or coefficient encoding")
    if tuple(model["evaluation"]["features"]) != EVAL_FEATURES:
        raise ValueError("evaluation feature order mismatch")
    if tuple(model["ordering"]["features"]) != ORDER_FEATURES:
        raise ValueError("ordering feature order mismatch")
    evaluation, ordering = model["evaluation"]["weights"], model["ordering"]["weights"]
    if len(evaluation) != len(EVAL_FEATURES) or len(ordering) != len(ORDER_FEATURES):
        raise ValueError("model weight count mismatch")
    encode_signed(evaluation + ordering)
    if max(coefficient_bounds(model)) >= 2**31:
        raise ValueError("model may overflow the signed-32 runtime accumulator")
    return model


def coefficient_bounds(model):
    """Triangle bounds for the exact feature ABI; arbitrary promoted material allowed."""
    w, order = model["evaluation"]["weights"], model["ordering"]["weights"]
    piece_bounds = [abs(w[k]) + 6 * abs(w[k + 5]) for k in range(5)]
    piece_bounds[0] += 6 * abs(w[11]) + abs(w[12]) + abs(w[13])
    evaluation = 62 * max(piece_bounds) + 6 * abs(w[10]) + abs(w[14]) + abs(w[15])
    material = max(abs(v) for v in w[:5])
    promotion = max(abs(v - w[0]) for v in w[1:5])
    ordering = (material * (abs(order[0]) + abs(order[1])) + promotion * abs(order[2])
                + 6 * abs(order[3]) + 7 * abs(order[4]))
    return evaluation, ordering


def canonical_bytes(model):
    return json.dumps(model, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")


def generated_sources(model):
    weights = model["evaluation"]["weights"] + model["ordering"]["weights"]
    encoded = encode_signed(weights)
    if decode_signed(encoded, 21) != weights:
        raise ValueError("coefficient round trip failed")
    if max(coefficient_bounds(model)) >= 2**31:
        raise ValueError("model may overflow the signed-32 runtime accumulator")
    digest = hashlib.sha256(canonical_bytes(model)).hexdigest()
    numbers = ",".join(map(str, encoded))
    c = f'''/* Generated by engines/model/codec.py; edit frozen.json, then regenerate.
   Canonical JSON SHA-256: {digest} */
#ifndef ROVE_E_FROZEN_H
#define ROVE_E_FROZEN_H
#include <stdint.h>
enum {{ ROVE_E_EVAL_COUNT=16, ROVE_E_ORDER_COUNT=5, ROVE_E_WEIGHT_COUNT=21 }};
static const unsigned char rove_e_encoded[]={{ {numbers} }};
/* The stream is fixed at build time and verified by codec.py, not external input. */
static void rove_e_weights(int16_t out[ROVE_E_WEIGHT_COUNT]){{
 unsigned p=0;
 for(unsigned i=0;i<ROVE_E_WEIGHT_COUNT;i++){{
  unsigned u=0,s=0,b;
  do{{b=rove_e_encoded[p++];u|=(b&127)<<s;s+=7;}}while(b&128);
  int v=(int)(u>>1);out[i]=(int16_t)((u&1)?-v-1:v);
 }}
}}
#endif
'''
    rust = f'''// Generated by engines/model/codec.py; edit frozen.json, then regenerate.
// Canonical JSON SHA-256: {digest}
pub const E_MODEL_BYTES: [u8; {len(encoded)}] = [{numbers}];
// The stream is fixed at build time and verified by codec.py, not external input.
pub fn model_weights() -> [i16; 21] {{
 let mut out = [0; 21];
 let mut p = 0;
 for value in &mut out {{
  let (mut u, mut s) = (0u32, 0);
  loop {{
   let b = E_MODEL_BYTES[p]; p += 1;
   u |= u32::from(b & 127) << s;
   if b & 128 == 0 {{ break; }}
   s += 7;
  }}
  let v = (u >> 1) as i16;
  *value = if u & 1 != 0 {{ -v - 1 }} else {{ v }};
 }}
 out
}}
'''
    return {"frozen.h": c, "frozen.rs": rust}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("check", "generate", "inspect"), nargs="?")
    parser.add_argument("--check", action="store_true", help="alias for the check operation")
    parser.add_argument("--out-dir", type=Path, default=HERE)
    args = parser.parse_args()
    if args.check and args.operation not in (None, "check"):
        parser.error("--check cannot be combined with generate or inspect")
    operation = args.operation or ("check" if args.check else "inspect")
    model = load_model()
    sources = generated_sources(model)
    if operation == "generate":
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for name, source in sources.items():
            (args.out_dir / name).write_text(source, encoding="utf-8", newline="\n")
    elif operation == "check":
        for name, source in sources.items():
            if (args.out_dir / name).read_text(encoding="utf-8") != source:
                raise SystemExit(f"stale generated source: {name}")
    print(json.dumps({"model": model["id"], "provenance": model["provenance"],
                      "canonical_sha256": hashlib.sha256(canonical_bytes(model)).hexdigest(),
                      "accumulator_abs_bounds": coefficient_bounds(model),
                      "weights": 21, "encoded_bytes": len(encode_signed(
                          model["evaluation"]["weights"] + model["ordering"]["weights"]))},
                     sort_keys=True))


if __name__ == "__main__":
    main()
