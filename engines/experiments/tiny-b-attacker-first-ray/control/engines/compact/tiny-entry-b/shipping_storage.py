if hashlib.sha256(_POLICY_BYTES).hexdigest()!=_POLICY_SHA256:
    raise ValueError('literal B storage policy changed')

def transform_source(data,*,family,lexer,reference,readable):
    if family!='B' or not isinstance(data,bytes) or not isinstance(readable,bytes):
        raise ValueError('exact B shipping/canonical bytes required')
    fixed=json.loads(_POLICY_BYTES)
    if hashlib.sha256(_POLICY_BYTES).hexdigest()!=_POLICY_SHA256:
        raise ValueError('literal B storage policy changed')
    reference._binding(readable,fixed['readable'],'B canonical readable')
    reference._binding(data,fixed['source'],'B shipping before storage18')
    mapping=fixed['mapping']
    if len(mapping)!=18 or len(set(mapping.values()))!=18 or set(mapping)&set(fixed['protected_shipping_names']):
        raise ValueError('fixed object-only mapping shape changed')
    text=readable.decode('utf-8')
    words=set(reference._WORD.findall(text))|set(reference._WORD.findall(reference._logical(text)[0]))
    if words&set(mapping.values()):raise ValueError('alias occurs in canonical B')
    candidate,counts,opaque=reference._rewrite(data,mapping,lexer=lexer)
    actual={name:counts[name] for name in mapping}
    saved=sum((len(name)-len(mapping[name]))*counts[name] for name in mapping)
    directives=sum(len(raw.encode()) for kind,raw in opaque if kind=='directive')
    ply=sum(token=='PLY' for _,_,token in lexer._identifier_spans(data.decode()))
    if (actual!=fixed['alpha_counts'] or saved!=fixed['alpha_saved_bytes']
        or len(data)-len(candidate)!=fixed['source_saved_bytes']
        or sum(counts.values())!=fixed['source_edits_count']
        or sum(v>0 for v in actual.values())!=fixed['mapping_used']
        or directives!=fixed['retained_directive_bytes'] or len(opaque)!=fixed['opaque_regions_preserved']
        or ply!=fixed['preserved_PLY_code_uses']):
        raise ValueError('fixed B storage counts/arithmetic/opaque regions changed')
    if sum(token=='PLY' for _,_,token in lexer._identifier_spans(candidate.decode()))!=ply:
        raise ValueError('PLY code uses changed')
    reference._binding(candidate,fixed['candidate'],'sole B storage source')
    return candidate,{'policy_sha256':_POLICY_SHA256,'original_policy_sha256':fixed['origin_policy_sha256'],
        'family':'B','mapping':mapping,'source_saved_bytes':saved,'source_edits_count':sum(counts.values()),
        'alpha_counts':actual,'resource_literals':{},'retained_directive_bytes':directives,
        'opaque_regions_preserved':len(opaque),'preserved_PLY_code_uses':ply,
        'source_only_proof':True,'native_equal_or_ABI_qualification_claimed':False}
