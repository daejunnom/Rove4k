"""Finite unselected valid-square scans for full A/B/C TEST-P4 sources.

Only the named outer scans change.  This is a pure source/cost projection,
not a producer selector, native-map exception, or runtime admission.  The
current full source must first be regenerated by its unchanged producer.
"""
from hashlib import sha256
import json


SCHEMA = "rove4k.selected-square-successor-experiment.v1"
FAMILIES = ("A", "B", "C")
INPUTS = {
    ("A", "test-p4"): (7624, "e3dde9e31bc95be91bdf49ffc9c4f7b72f3fc816402c00855410a82c9d1e5ec3"),
    ("B", "test-p4"): (7934, "09546a75f5e417125ec033994fec52b1e23da4d504e5146a54cead53966136ce"),
    ("C", "test-p4"): (8228, "43f4d27643a29484c4fa8f0e29072ccea460ca931a4e5855824bca4dcd70722f"),
}
# The exact final-source pins bind these spelling-specific loops.  No ray,
# bitboard/ctz walk, TT initialization, or inner 0x88 guard is a target.
SPANS = {
    "A": (
        ("dead-valid-squares", "for(L q=0;q<128;q++)if(!(q&0x88)){", "for(L q=0;q<128;q=q+9&~8){"),
        ("walker-valid-squares", "for(L o=0;o<128;o++){if(o&0x88){o+=7;continue;}", "for(L o=0;o<128;o=o+9&~8){"),
    ),
    "B": (
        ("material-valid-squares", "X(I q=0;q<128;q++)W(!(q&136)){", "X(I q=0;q<128;q=q+9&~8){"),
    ),
    "C": (
        ("dead-valid-squares", "for(int q=0;q<128;q++)if(!(q&0x88)){", "for(int q=0;q<128;q=q+9&~8){"),
        ("walker-valid-squares", "for(int o=0;o<128;o++){if(o&0x88){o+=7;continue;}", "for(int o=0;o<128;o=o+9&~8){"),
    ),
}


def require(value, message):
    if not value:
        raise ValueError(message)


def pin(data):
    require(type(data) is bytes, "actual immutable source bytes required")
    return dict(bytes=len(data), sha256=sha256(data).hexdigest())


def _json(value):
    try:
        return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)
    except (TypeError, ValueError) as error:
        raise ValueError("finite JSON source proof required") from error


def iteration_witness():
    """Enumerate the three bounded integer controls, without running C/engines.

    This witness concerns iteration order only.  The edited openings leave
    every body byte outside the spans; the C signed-int domain is 0..128.
    """
    expected = [16 * rank + file for rank in range(8) for file in range(8)]
    guarded = [q for q in range(128) if not q & 0x88]
    skipped, q = [], 0
    while q < 128:
        if q & 0x88:
            q += 7
        else:
            skipped.append(q)
        q += 1
    skipped_exit = q
    successor, q, maximum_sum = [], 0, 0
    while q < 128:
        successor.append(q)
        maximum_sum = max(maximum_sum, q + 9)
        q = (q + 9) & ~8
    require(guarded == skipped == successor == expected and len(expected) == 64
            and expected[-1] == 119 and q == skipped_exit == maximum_sum == 128,
            "bounded ordered valid-square witness differs")
    return dict(kind="pure-ordered-integer-enumeration", values=expected,
        count=64, first=0, last=119, exit=128, maximum_addition=128,
        guarded_body_visits_equal=True, hole_skip_body_visits_equal=True,
        source_bodies_preserved_separately=True, compiled_C_executed=False)


def _project(source, specifications):
    """Splice unique literal openings; kept separate for pure mechanism tests."""
    require(type(source) is bytes and type(specifications) is tuple and specifications,
            "finite immutable source and literal span tuple required")
    rows = []
    for role, before, after in specifications:
        require(type(role) is str and type(before) is str and type(after) is str
                and before and after, "literal source span required")
        old, new = before.encode("ascii"), after.encode("ascii")
        require(source.count(old) == 1, "one exact outer scan required: " + role)
        rows.append((source.index(old), old, new, role))
    rows.sort()
    parts, edits, gaps, old_at, new_at = [], [], [], 0, 0
    for at, before, after, role in rows:
        require(at >= old_at, "outer-scan edits overlap")
        gap = source[old_at:at]
        parts.append(gap)
        gaps.append(dict(input_begin=old_at, output_begin=new_at, **pin(gap)))
        new_at += len(gap)
        edits.append(dict(role=role, input_begin=at, output_begin=new_at,
                          before=before.decode("ascii"), after=after.decode("ascii")))
        parts.append(after)
        old_at, new_at = at + len(before), new_at + len(after)
    tail = source[old_at:]
    parts.append(tail)
    gaps.append(dict(input_begin=old_at, output_begin=new_at, **pin(tail)))
    return b"".join(parts), edits, gaps


def _inverse(candidate, edits):
    restored = candidate
    require(type(edits) is list and 1 <= len(edits) <= 2,
            "one or two exact outer-scan edits required")
    for row in reversed(edits):
        require(type(row) is dict and set(row) ==
                {"role", "input_begin", "output_begin", "before", "after"}
                and type(row["input_begin"]) is int and type(row["output_begin"]) is int
                and type(row["role"]) is str and type(row["before"]) is str
                and type(row["after"]) is str and 0 < len(row["before"]) <= 128
                and 0 < len(row["after"]) <= 128,
                "exact typed source inverse span required")
        at = row["output_begin"]
        old, new = row["before"].encode("ascii"), row["after"].encode("ascii")
        require(0 <= at <= len(restored) and restored[at:at + len(new)] == new,
                "outer-scan inverse span differs")
        restored = restored[:at] + old + restored[at + len(new):]
    return restored


def transform_source(source, *, family, profile_id="test-p4"):
    require(type(family) is str and type(profile_id) is str
            and (family, profile_id) in INPUTS, "explicit finite A/B/C TEST-P4 required")
    require(type(source) is bytes and (len(source), sha256(source).hexdigest()) == INPUTS[(family, profile_id)]
            and b"\r" not in source, "fresh selected full source differs from its exact pin")
    result, edits, gaps = _project(source, SPANS[family])
    require(_inverse(result, edits) == source, "outer-scan full inverse differs")
    for gap in gaps:
        before = source[gap["input_begin"]:gap["input_begin"] + gap["bytes"]]
        after = result[gap["output_begin"]:gap["output_begin"] + gap["bytes"]]
        require(before == after and pin(after) == {key: gap[key] for key in ("bytes", "sha256")},
                "outer-scan protected body/complement differs")
    return result, dict(schema=SCHEMA, family=family, profile_id=profile_id,
        variant="ordered-valid-square-successor", input=pin(source), output=pin(result),
        edits=edits, protected_gaps=gaps, iteration=iteration_witness(), full_inverse=True,
        source_regions=len(edits), raw_source_delta=len(result) - len(source),
        scope="only the named outer scan openings; all ordered bodies and other source bytes preserved",
        resources_changed=False, features_removed=False, B_bitboard_walker_changed=False,
        engine_executed=False, runtime_qualified=False, rules_qualified=False,
        production_selected=False)


def restore_source(candidate, proof):
    require(type(candidate) is bytes and type(proof) is dict and proof.get("schema") == SCHEMA
            and type(proof.get("family")) is str and type(proof.get("profile_id")) is str,
            "exact square-successor source proof required")
    key = proof["family"], proof["profile_id"]
    require(key in INPUTS and len(candidate) <= INPUTS[key][0]
            and pin(candidate) == proof.get("output"), "square-successor output identity differs")
    restored = _inverse(candidate, proof.get("edits"))
    repeated, canonical = transform_source(restored, family=key[0], profile_id=key[1])
    require(repeated == candidate and _json(canonical) == _json(proof),
            "square-successor proof differs from its complete canonical projection")
    return restored
