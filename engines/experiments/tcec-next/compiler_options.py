#!/usr/bin/env python3
"""Measure -Os/-O2/-O3 on explicit full-C source-JIT build inputs.

This is an experiment, not a source generator or an expected-value updater.
The supplied baseline must already have been regenerated by its source builder.
Each level compiles and packages the same source twice. Runtime/efficiency and
playing-strength qualification remain separate from this build measurement.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
import lzma
import os
from pathlib import Path
import platform
import shutil
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[3]
SELF = 'engines/experiments/tcec-next/compiler_options.py'
HOST = 'engines/experiments/tcec-scope/build.py'
HOST_PIN = '5fa10c6f8f032be374bf3a86bbe6ca558076630a2cc3170b41890f691688f563'
PACKAGE = 'engines/scripts/source_package.py'
PACKAGE_PIN = '4c3775e713b093de39cb54e12abdef29793dd924731f1b3014c406d1df4e4f19'
LEVELS = ('-Os', '-O2', '-O3')


def require(value, message):
    if not value:
        raise ValueError(message)


def pin(data):
    return {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def select_compiler(compiler, level):
    """Change exactly one admitted optimization token, preserving its width."""
    require(level in LEVELS, 'only -Os/-O2/-O3 are in this finite comparison')
    require(isinstance(compiler, (tuple, list)) and all(type(x) is str for x in compiler),
            'literal compiler argv required')
    positions = [i for i, value in enumerate(compiler) if value.startswith('-O')]
    require(len(positions) == 1 and compiler[positions[0]] in LEVELS,
            'exactly one admitted optimization level required')
    result = list(compiler)
    index = positions[0]
    old = result[index]
    result[index] = level
    require(len(old.encode('ascii')) == len(level.encode('ascii')) == 3,
            'the zero-byte header comparison requires equal-width options')
    proof = {'format': 1, 'kind': 'compiler-optimization-level',
             'original': list(compiler), 'candidate': result,
             'index': index, 'before': old, 'after': level,
             'source_changed': False,
             'semantic_claim': 'same C source; compiler correctness and target performance require separate evidence'}
    return result, proof


def restore_compiler(compiler, proof):
    require(proof['format'] == 1 and proof['kind'] == 'compiler-optimization-level',
            'unknown compiler proof')
    require(list(compiler) == proof['candidate'], 'candidate compiler differs')
    result, replay = select_compiler(proof['original'], proof['after'])
    require(result == list(compiler) and replay == proof, 'compiler proof differs')
    return list(proof['original'])


def normalized(path):
    data = path.read_bytes().replace(b'\r\n', b'\n')
    require(b'\r' not in data, 'lone CR in source')
    return data


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def source_name(name):
    path = Path(name)
    blocked = ('node_modules', 'dist', 'dist-server', 'build', 'coverage',
               'models', 'checkpoints', '.cache')
    low = path.name.lower()
    require(not path.is_absolute() and '..' not in path.parts
            and path.parts and path.parts[0] == 'engines'
            and not any(part in blocked for part in path.parts)
            and not low.startswith('.env')
            and not any(word in low for word in ('credential', 'secret', 'service_account',
                                               'service-account', 'api_key', 'api-key'))
            and low not in ('inventory.json', 'package-lock.json', 'id_rsa', 'id_ed25519', 'id_ecdsa'),
            'not an admitted named engine source: ' + name)
    return path


def checked(path, expected, prefix=None):
    data = path.read_bytes()
    require(pin(data) == (expected if prefix is None else
            {'bytes': expected[prefix + '_bytes'], 'sha256': expected[prefix + '_sha256']}),
            'explicit baseline artifact differs: ' + str(path))
    return data


def frozen_sources(build, manifest, target):
    """Copy only named, hash-checked baseline sources, not generated binaries."""
    for table, directory, destination in (
            (manifest['inputs'], build/'inputs', target/'inputs'),
            (manifest['control_source_closure'], build/'producer-repo', target/'producer-repo')):
        for name, expected in table.items():
            relative = source_name(name)
            data = checked(directory/relative, expected)
            path = destination/relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    own = normalized(Path(__file__))
    path = target/'inputs'/SELF
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(own)
    return {**manifest['inputs'], SELF: pin(own)}


def run(args):
    out = args.out.resolve()
    require(sys.platform == 'linux', 'Linux source-JIT experiment required')
    require(args.out.is_absolute() and not out.exists()
            and not any((p/'.git').exists() for p in (out, *out.parents)),
            'new absolute output outside every Git checkout required')
    host_source = normalized(ROOT/HOST)
    require(pin(host_source)['sha256'] == HOST_PIN, 'explicit shared host revision changed')
    host_module = load('compiler_options_host', ROOT/HOST)
    host_module.LIMITS = {**host_module.LIMITS, 'aggregate_wall': 600,
        'per_command_wall': 120, 'parent_AS': 2 << 30, 'parent_CPU': 180,
        'parent_CPU_hard': 210, 'child_AS': 2 << 30, 'child_CPU': 90,
        'tool_output_bytes': 2 << 20}
    out.mkdir()
    report = {'format': 1, 'kind': 'full-C-compiler-options-measurement',
              'complete': False, 'commands': [], 'profiles': {},
              'limits': host_module.LIMITS,
              'scope': 'explicit hash-checked source-produced baselines; source generation is not rerun by this tool',
              'qualification': {'runtime': False, 'target_performance': False, 'playing_strength': False},
              'contention': 'pilot; concurrent jobs may exist; elapsed values are not an adoption benchmark',
              'environment': {'affinity': sorted(os.sched_getaffinity(0)),
                              'platform': platform.platform(),
                              'topology_scope': 'local exposed VM topology, not a physical-core or TCEC-host attestation'},
              'source_inputs': {SELF: pin(normalized(Path(__file__))), HOST: pin(host_source)}}

    def save():
        (out/'comparison.json').write_text(json.dumps(report, indent=2)+'\n')
    save()
    host = host_module.Host(out, report, save)
    try:
        for baseline in args.build:
            require(baseline.is_absolute(), 'explicit absolute source-produced baseline required')
            build = baseline.resolve()
            raw = (build/'build.json').read_bytes()
            original = json.loads(raw)
            require(original['class'] == 'tcec-full-C-v1' and original['complete']
                    and original['reproducible'] is True, 'complete full-C baseline required')
            entry = original['entry']
            require(entry not in report['profiles'], 'duplicate entry')
            expected = original['expected_contract']
            source = checked(build/'main.c', expected, 'source')
            old_native = checked(build/'native/x', expected, 'native')
            old_whole = checked(build/'x', expected, 'whole')
            old_header = checked(build/'header.sh', expected, 'header')
            checked(build/'payload.lzma', expected, 'payload')
            require(original['compiler'].count('-Os') == 1, 'the comparison control must be -Os')
            compiler = shutil.which(original['compiler'][0])
            require(compiler is not None, 'baseline logical compiler unavailable')
            compiler = os.path.realpath(compiler)
            row = {'baseline_build': str(build), 'baseline_build_pin': pin(raw),
                   'baseline_artifacts': expected, 'levels': {}, 'compiler_path': compiler}
            report['profiles'][entry] = row
            for level in LEVELS:
                target = out/(entry + '-' + level[1:])
                target.mkdir()
                inputs = frozen_sources(build, original, target)
                package_bytes = (target/'inputs'/PACKAGE).read_bytes()
                require(pin(package_bytes)['sha256'] == PACKAGE_PIN,
                        'this experiment admits the unchanged original pipe wrapper')
                packaging = load('compiler_package_' + entry + level[1:], target/'inputs'/PACKAGE)
                argv, proof = select_compiler(original['compiler'], level)
                require(restore_compiler(argv, proof) == original['compiler'], 'compiler argv inverse failed')
                header = packaging.tcec_header(compiler=argv)
                require(len(header) == len(old_header), 'whole header length changed')
                artifact = copy.deepcopy(original)
                artifact.update(complete=False, reproducible=False, inputs=inputs, attempts=[],
                    commands=[], compiler=argv, compiler_comparison=proof,
                    source_authority='explicit baseline source, no historical binary as generator',
                    qualification={**original['qualification'], 'selection': 'experimental-measurement', 'runtime': False},
                    wrapper_contract=packaging.tcec_contract(compiler=argv))
                artifact['selected_verifier']['inputs'] = inputs
                artifact['source_proofs'] = original['source_proofs'] + [
                    {'stage': 'compiler-optimization-level', 'proof': proof, 'full_inverse': True,
                     'source_changed': False}]
                (target/'build.json').write_text(json.dumps(artifact, indent=2)+'\n')
                for attempt in ('first', 'repeat'):
                    directory = target/attempt
                    native_dir = directory/'native'
                    native_dir.mkdir(parents=True)
                    command = [compiler, *argv[1:]]
                    start = len(report['commands'])
                    host.run(command, cwd=native_dir, kind=entry+'-'+level[1:]+'-'+attempt, data=source)
                    native = (native_dir/'x').read_bytes()
                    if level == '-Os':
                        require(native == old_native, 'current compiler did not reproduce supplied -Os native')
                    whole = packaging.package_tcec(source, original['compression'], compiler=argv)
                    require(len(whole) == len(old_whole) and whole.startswith(header),
                            'actual complete file did not preserve byte length')
                    if level == '-Os':
                        require(whole == old_whole, 'original complete file was not reproduced')
                    payload = whole[len(header):]
                    decoder = lzma.LZMADecompressor(format=lzma.FORMAT_ALONE)
                    require(decoder.decompress(payload) == source and decoder.eof and not decoder.unused_data,
                            'strict source restoration failed')
                    for name, data in (('main.c', source), ('header.sh', header), ('payload.lzma', payload), ('x', whole)):
                        (directory/name).write_bytes(data)
                    (directory/'x').chmod(0o700)
                    (directory/'source-proof.json').write_text(json.dumps(artifact['source_proofs'], indent=2)+'\n')
                    fields = {prefix+'_'+key: value for prefix, data in
                              (('source', source), ('native', native), ('whole', whole),
                               ('header', header), ('payload', payload)) for key, value in pin(data).items()}
                    artifact['attempts'].append({'directory': attempt, **fields,
                                                'source_proofs': artifact['source_proofs']})
                    artifact['commands'].extend(report['commands'][start:])
                first, repeat = artifact['attempts']
                require({k:v for k,v in first.items() if k != 'directory'} ==
                        {k:v for k,v in repeat.items() if k != 'directory'}, 'fresh attempts differ')
                fields = {key: first[key] for key in expected}
                artifact.update(expected_contract=fields, complete=True, reproducible=True,
                                producer_source_closure_unchanged=True)
                for name in ('main.c', 'native/x', 'x', 'header.sh', 'payload.lzma', 'source-proof.json'):
                    (target/name).parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(target/'first'/name, target/name)
                (target/'x').chmod(0o700)
                (target/'native/x').chmod(0o700)
                (target/'build.json').write_text(json.dumps(artifact, indent=2)+'\n')
                row['levels'][level] = {'build': str(target), **fields,
                                       'actual_whole_delta': len(whole)-len(old_whole)}
                save()
        report['compiler_version'] = host.run([compiler, '--version'], cwd=out, kind='compiler-version').decode()
        report['compiler_target'] = host.run([compiler, '-dumpmachine'], cwd=out, kind='compiler-target').decode().strip()
    except BaseException as error:
        report['failure'] = {'type': type(error).__name__, 'message': str(error)}
        save()
        raise
    finally:
        host.close()
    report['complete'] = True
    save()
    print(json.dumps({'out': str(out), 'entries': list(report['profiles']), 'complete': True}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build', type=Path, nargs='+', required=True)
    parser.add_argument('--out', type=Path, required=True)
    run(parser.parse_args())
